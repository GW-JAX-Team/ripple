import jax.numpy as jnp


def IMRPhenomX_PNR_evaluate_coefficient_array(
    coeff_array: jnp.ndarray, eta: float, chi: float, costheta: float
) -> float:
    """
    Evaluate polynomial using coefficient array.

    Computes: sum_{i,j,k} coeff_array[i,j,k] * eta^i * chi^j * costheta^k

    Parameters
    ----------
    coeff_array : jnp.ndarray
        4x4x5 array of polynomial coefficients
    eta : float
        Symmetric mass ratio
    chi : float
        Effective single spin magnitude
    costheta : float
        Cosine of spin orientation angle

    Returns
    -------
    float
        Evaluated polynomial
    """
    poly_sum = 0.0

    for i in range(4):
        for j in range(4):
            for k in range(5):
                poly_sum += (
                    coeff_array[i, j, k]
                    * jnp.power(eta, i)
                    * jnp.power(chi, j)
                    * jnp.power(costheta, k)
                )

    return poly_sum


